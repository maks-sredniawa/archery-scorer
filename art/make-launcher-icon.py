#!/usr/bin/env python3
"""Generate the launcher icon and the 512² Play listing asset from `mark.py`.

Writes, all of them derived and none of them hand-editable:

    app/src/main/res/drawable/ic_launcher_foreground.xml
    app/src/main/res/drawable/ic_launcher_monochrome.xml
    app/src/main/res/drawable/ic_notification.xml
    app/src/main/res/mipmap-{m,h,xh,xxh,xxx}dpi/ic_launcher{,_round}.webp
    art/play-icon-512.png

    app/src/main/res/drawable/ic_launcher_background.xml

`ic_launcher_background.xml` is one flat rectangle, and it is *generated* all the same: its colour is
`mark.GROUND`, and a second copy of that colour in a file nobody regenerates is exactly the drift the
hand-written version of it had.

    python3 art/make-launcher-icon.py
"""

import math
from pathlib import Path

from PIL import Image, ImageDraw

import mark

ART = Path(__file__).parent
RES = ART.parent / "app/src/main/res"

CANVAS = 108  # adaptive-icon canvas, in dp
VISIBLE = 72  # the most any launcher shows of it — what the flat assets are cropped to, and mark.FRAME

# A launcher may mask the icon down to a 66dp circle, so anything outside that gets clipped. The
# face is meant to be cropped and is exempt; the arrow is not, and main() measures it rather than
# trusting the numbers in mark.py.
SAFE_DIAMETER = 66

DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
SS = 20  # supersample factor for the raster assets

# A notification small icon has no adaptive-icon safe zone to respect — Android draws it as a
# silhouette in a 24dp slot — so the arrow is scaled to fill nearly the whole viewport.
NOTIFICATION_ART = 96

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!--
  The app mark. Original art, declared in art/mark.py and generated by
  art/make-launcher-icon.py — regenerate rather than editing the path data here. The gap round the
  arrow is a clip on the face, not a shape painted in the ground colour.
-->
"""

MONOCHROME_HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!--
  The themed-icon layer: the arrow alone, centred; art/README.md says why. Generated by
  art/make-launcher-icon.py from art/mark.py — regenerate rather than editing the path data here.
-->
"""

NOTIFICATION_HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!--
  The monochrome layer's arrow, scaled up to fill a notification icon. Generated by
  art/make-launcher-icon.py — regenerate rather than editing the path data here.

  A notification small icon is drawn as a **silhouette**: Android throws away every colour in
  it and tints the non-transparent pixels, which is why this is the arrow alone rather than the
  full-colour launcher art.
-->
"""

NOTIFICATION = """{header}<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="108"
    android:viewportHeight="108"
    android:tint="#FFFFFF">
{paths}</vector>
"""

BACKGROUND = """<?xml version="1.0" encoding="utf-8"?>
<!--
  The adaptive icon's back layer: one flat field, mark.GROUND. Generated by
  art/make-launcher-icon.py — regenerate rather than editing the colour here, because the colour
  lives in art/mark.py and this is a rendering of it.

  A themed launcher (API 33+) ignores this layer entirely and tints the monochrome one flat, so
  this is what a *standard* icon shows and nothing here is load-bearing for theming.
-->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
  <path
      android:fillColor="{colour}"
      android:pathData="M0,0h108v108h-108z" />
</vector>
"""

VECTOR = """{header}<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{paths}</vector>
"""

PATH = """  <path
      android:fillColor="{colour}"
      android:pathData="{data}" />
"""

# The cut is the canvas with the cut contour wound against it: non-zero leaves everything but the
# contour, so the clip keeps the face everywhere except the gap.
CLIPPED = """  <group>
    <clip-path android:pathData="M0,0h108v108h-108z{cut}" />
    <path
        android:fillColor="{colour}"
        android:pathData="{data}" />
  </group>
"""


def hex_of(rgb):
    return "#{:02X}{:02X}{:02X}".format(*rgb)


def joined(parts, tf):
    return "".join(mark.path_data(e, tf) for e in parts)


def foreground_paths(tf):
    out = []
    for layer in mark.LAYERS:
        fill = {"colour": hex_of(layer.ink), "data": joined(layer.parts, tf)}
        if layer.cut:
            cut = mark.path_data(mark.Subpath(layer.cut.d, hole=True), tf)
            out.append(CLIPPED.format(cut=cut, **fill))
        else:
            out.append(PATH.format(**fill))
    return "".join(out)


def arrow_size():
    """The arrow's longest side at the launcher's own scale, so the monochrome arrow matches it."""
    x0, y0, x1, y1 = mark.bounds(mark.ARROW)
    return max(x1 - x0, y1 - y0) * VISIBLE / mark.FRAME


def render(size, mask_circle=False):
    """The composed icon — flat ground, the mark's layers — cropped to the visible 72dp."""
    big = CANVAS * SS
    img = Image.new("RGBA", (big, big), mark.GROUND + (255,))
    tf = mark.fit(big, VISIBLE * SS)

    # Each layer goes on its own sheet so its holes and its cut are punched to full transparency and
    # let what is under them show through, as the vector's winding and clip do. Painting them back
    # in the ground's colour would look identical on a flat ground and stop being true the day the
    # ground is anything else.
    #
    # Declaration order, because the raster has no winding rule: a solid declared after a hole lands
    # inside it, as the face's middle does inside its last ring gap.
    for layer in mark.LAYERS:
        sheet = Image.new("RGBA", (big, big), (0, 0, 0, 0))
        d = ImageDraw.Draw(sheet)
        for e in layer.parts:
            d.polygon(mark.outline(e, tf), fill=(0, 0, 0, 0) if e.hole else layer.ink + (255,))
        if layer.cut:
            d.polygon(mark.outline(layer.cut, tf), fill=(0, 0, 0, 0))
        img.alpha_composite(sheet)

    inset = (CANVAS - VISIBLE) // 2 * SS
    img = img.crop((inset, inset, big - inset, big - inset)).resize((size, size), Image.LANCZOS)

    if mask_circle:
        mask = Image.new("L", (size * 4, size * 4), 0)
        ImageDraw.Draw(mask).ellipse((0, 0, size * 4 - 1, size * 4 - 1), fill=255)
        img.putalpha(mask.resize((size, size), Image.LANCZOS))
    return img


def reach(parts, tf):
    """How far the art itself reaches from the canvas centre — not its bounding box, whose corners
    are empty for a diagonal arrow and would report clipping that isn't there."""
    return max(
        math.hypot(px - CANVAS / 2, py - CANVAS / 2)
        for e in parts
        if not e.hole
        for px, py in mark.outline(e, tf)
    )


def main():
    written = []
    fg = mark.fit(CANVAS, VISIBLE)
    mono = mark.fit_bounds(CANVAS, arrow_size(), mark.ARROW)

    background = RES / "drawable" / "ic_launcher_background.xml"
    background.write_text(BACKGROUND.format(colour=hex_of(mark.GROUND)))
    written.append(background)

    foreground = RES / "drawable" / "ic_launcher_foreground.xml"
    foreground.write_text(VECTOR.format(header=HEADER, paths=foreground_paths(fg)))
    written.append(foreground)

    monochrome = RES / "drawable" / "ic_launcher_monochrome.xml"
    monochrome.write_text(VECTOR.format(
        header=MONOCHROME_HEADER,
        paths=PATH.format(colour="#FFFFFF", data=joined(mark.ARROW, mono)),
    ))
    written.append(monochrome)

    notification = RES / "drawable" / "ic_notification.xml"
    notification.write_text(NOTIFICATION.format(
        header=NOTIFICATION_HEADER,
        paths=PATH.format(colour="#FFFFFF", data=joined(mark.ARROW, mark.fit_bounds(CANVAS, NOTIFICATION_ART, mark.ARROW))),
    ))
    written.append(notification)

    for density, size in DENSITIES.items():
        for name, circle in (("ic_launcher", False), ("ic_launcher_round", True)):
            path = RES / f"mipmap-{density}" / f"{name}.webp"
            render(size, mask_circle=circle).save(path, "WEBP", lossless=True, quality=100)
            written.append(path)

    play = ART / "play-icon-512.png"
    render(512).convert("RGB").save(play, "PNG", optimize=True)  # Play rejects alpha
    written.append(play)

    safe = SAFE_DIAMETER / 2
    for name, tf in (("arrow", fg), ("monochrome arrow", mono)):
        r = reach(mark.ARROW, tf)
        print(f"{name} reaches {r:.1f}dp from centre vs {safe:.0f}dp safe radius"
              f" — {'inside' if r <= safe else 'CLIPPED by a circular mask'}")
    print("face bleeds past the visible square by design and is exempt")
    for p in written:
        print(f"  {p.relative_to(ART.parent)}")


if __name__ == "__main__":
    main()
